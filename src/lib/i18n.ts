export function t(lang: LangCode, key: string, vars?: Record<string, string>): string {
  const str = translations[lang]?.[key] || translations.en[key] || key
  if (!vars) return str
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{${k}}`, v), str)
}

